/// Date filter for aggregation queries
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum DateFilter {
    /// Filter transactions from a specific date onwards
    From(NaiveDate),
    /// Filter transactions up to a specific date
    To(NaiveDate),
    /// Filter transactions within a date range (inclusive)
    Between(NaiveDate, NaiveDate),
    /// Filter transactions on an exact date
    Exact(NaiveDate),
}

impl DateFilter {
    /// Generate SQL fragment + bind values for date filtering. PR5
    /// (Fable-5 #25): dates now bind rather than interpolate. The wire
    /// format is still `YYYY-MM-DD` so SQLite's `DATE()` comparison works
    /// against the header's `'YYYY-MM-DD HH:MM:SS'` timestamp exactly as
    /// before.
    pub fn to_sql_parts(&self) -> (String, Vec<BindValue>) {
        match self {
            DateFilter::From(date) => (
                "DATE(th.TRANSACTION_DATE) >= ?".to_string(),
                vec![BindValue::Str(date.format("%Y-%m-%d").to_string())],
            ),
            DateFilter::To(date) => (
                "DATE(th.TRANSACTION_DATE) <= ?".to_string(),
                vec![BindValue::Str(date.format("%Y-%m-%d").to_string())],
            ),
            DateFilter::Between(from, to) => (
                "DATE(th.TRANSACTION_DATE) BETWEEN ? AND ?".to_string(),
                vec![
                    BindValue::Str(from.format("%Y-%m-%d").to_string()),
                    BindValue::Str(to.format("%Y-%m-%d").to_string()),
                ],
            ),
            DateFilter::Exact(date) => (
                "DATE(th.TRANSACTION_DATE) = ?".to_string(),
                vec![BindValue::Str(date.format("%Y-%m-%d").to_string())],
            ),
        }
    }
}

/// Amount filter for aggregation queries
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum AmountFilter {
    /// Filter transactions with amount greater than or equal to value
    GreaterThan(i64),
    /// Filter transactions with amount less than or equal to value
    LessThan(i64),
    /// Filter transactions within an amount range (inclusive)
    Between(i64, i64),
    /// Filter transactions with exact amount
    Exact(i64),
    /// No amount filter
    None,
}

impl AmountFilter {
    /// Generate SQL fragment + bind values for amount filtering.
    /// `AmountFilter::None` returns an empty tuple.
    pub fn to_sql_parts(&self) -> (String, Vec<BindValue>) {
        match self {
            AmountFilter::GreaterThan(amount) => (
                "th.TOTAL_AMOUNT >= ?".to_string(),
                vec![BindValue::I64(*amount)],
            ),
            AmountFilter::LessThan(amount) => (
                "th.TOTAL_AMOUNT <= ?".to_string(),
                vec![BindValue::I64(*amount)],
            ),
            AmountFilter::Between(min, max) => (
                "th.TOTAL_AMOUNT BETWEEN ? AND ?".to_string(),
                vec![BindValue::I64(*min), BindValue::I64(*max)],
            ),
            AmountFilter::Exact(amount) => (
                "th.TOTAL_AMOUNT = ?".to_string(),
                vec![BindValue::I64(*amount)],
            ),
            AmountFilter::None => (String::new(), Vec::new()),
        }
    }

    /// Check if the filter has any condition
    pub fn has_condition(&self) -> bool {
        !matches!(self, AmountFilter::None)
    }
}

/// Category filter for aggregation queries
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum CategoryFilter {
    /// Filter by category1 code only
    Category1(String),
    /// Filter by category1 and category2 codes
    Category2(String, String),
    /// Filter by category1, category2, and category3 codes
    Category3(String, String, String),
    /// No category filter
    None,
}

impl CategoryFilter {
    /// Generate SQL fragment + bind values for category filtering.
    ///
    /// PR5 (Fable-5 #25): category codes bind rather than interpolate
    /// through the old `escape_sql_literal` helper.
    ///
    /// PR6 (Fable-5 #17): `Category2` and `Category3` now reference
    /// `td.CATEGORY{2,3}_CODE` because those columns live on
    /// `TRANSACTIONS_DETAIL`, not `TRANSACTIONS_HEADER`. The old shape
    /// (`th.CATEGORY2_CODE`) matched no existing column and would have
    /// crashed with `no such column` the first time the drilldown UI
    /// wired the filter through — see also the injection-safety pin in
    /// tests which switched to `Category1` for exactly that reason.
    ///
    /// Callers: `Category2`/`Category3` filters are only valid when
    /// the surrounding query joins `TRANSACTIONS_DETAIL td` — i.e. inside
    /// `build_detail_query` (`GroupBy::Category2/3/Product`). Applying
    /// them to a header-only query (`GroupBy::Category1/Shop/Date`) or
    /// to `build_account_aggregation_query` will still fail with
    /// `no such column: td.*`; that surfaces the misuse fast rather
    /// than silently returning the wrong rows.
    pub fn to_sql_parts(&self) -> (String, Vec<BindValue>) {
        match self {
            CategoryFilter::Category1(cat1) => (
                "th.CATEGORY1_CODE = ?".to_string(),
                vec![BindValue::Str(cat1.clone())],
            ),
            CategoryFilter::Category2(cat1, cat2) => (
                "td.CATEGORY1_CODE = ? AND td.CATEGORY2_CODE = ?".to_string(),
                vec![BindValue::Str(cat1.clone()), BindValue::Str(cat2.clone())],
            ),
            CategoryFilter::Category3(cat1, cat2, cat3) => (
                "td.CATEGORY1_CODE = ? AND td.CATEGORY2_CODE = ? AND td.CATEGORY3_CODE = ?"
                    .to_string(),
                vec![
                    BindValue::Str(cat1.clone()),
                    BindValue::Str(cat2.clone()),
                    BindValue::Str(cat3.clone()),
                ],
            ),
            CategoryFilter::None => (String::new(), Vec::new()),
        }
    }

    /// Check if the filter has any condition
    pub fn has_condition(&self) -> bool {
        !matches!(self, CategoryFilter::None)
    }
}

