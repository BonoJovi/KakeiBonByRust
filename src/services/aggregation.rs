/// Value bound into a prepared statement. Type-erased so a heterogeneous
/// list of binds can be threaded through the query builders and applied to
/// the sqlx query in one place at execute time. Kept as `Clone` so tests
/// can inspect what a builder produced without consuming it.
///
/// PR5 replaces the previous mix of `format!()` interpolation +
/// `escape_sql_literal` (SQLite-only single-quote doubling) with `?`
/// placeholders across the aggregation module. `escape_sql_literal` had no
/// path to injection today because every value it touched came from
/// controlled internal sources — CATEGORY*_CODE values are generated by
/// the category service, and `lang` is the current UI locale from
/// `settings.language` — but any new filter that skipped the helper would
/// have become a live injection site on its first use.
#[derive(Debug, Clone)]
pub enum BindValue {
    I64(i64),
    Str(String),
}

impl From<i64> for BindValue {
    fn from(v: i64) -> Self {
        BindValue::I64(v)
    }
}

impl From<&str> for BindValue {
    fn from(v: &str) -> Self {
        BindValue::Str(v.to_string())
    }
}

impl From<String> for BindValue {
    fn from(v: String) -> Self {
        BindValue::Str(v)
    }
}

/// Bind every value in `binds` onto `query` in order. Kept as a small
/// helper (rather than a trait extension) so both `query` and `query_as`
/// call sites can lean on the same code path without generic gymnastics.
fn bind_all<'q, T>(
    mut query: sqlx::query::QueryAs<'q, sqlx::Sqlite, T, sqlx::sqlite::SqliteArguments<'q>>,
    binds: Vec<BindValue>,
) -> sqlx::query::QueryAs<'q, sqlx::Sqlite, T, sqlx::sqlite::SqliteArguments<'q>>
where
    T: for<'r> sqlx::FromRow<'r, sqlx::sqlite::SqliteRow>,
{
    for value in binds {
        query = match value {
            BindValue::I64(v) => query.bind(v),
            BindValue::Str(v) => query.bind(v),
        };
    }
    query
}

