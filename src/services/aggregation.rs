/// Build WHERE clause from aggregation filter. Returns the parameterized
/// SQL fragment (with `?` placeholders) and the ordered list of bind
/// values the caller must feed to sqlx before `fetch_all`. PR5 (Fable-5
/// #25).
pub fn build_where_clause(user_id: i64, filter: &AggregationFilter) -> (String, Vec<BindValue>) {
    let mut conditions: Vec<String> = Vec::new();
    let mut binds: Vec<BindValue> = Vec::new();

    conditions.push("th.USER_ID = ?".to_string());
    binds.push(BindValue::I64(user_id));

    let (date_sql, date_binds) = filter.date.to_sql_parts();
    conditions.push(date_sql);
    binds.extend(date_binds);

    // Exclude TRANSFER from category-based aggregations (always results in 0)
    conditions.push("th.CATEGORY1_CODE != 'TRANSFER'".to_string());

    // Exclude scheduled transactions by default
    if !filter.include_scheduled {
        conditions.push("th.IS_SCHEDULED = 0".to_string());
    }

    // Add amount filter if present
    if let Some(ref amount) = filter.amount {
        if amount.has_condition() {
            let (sql, more) = amount.to_sql_parts();
            conditions.push(sql);
            binds.extend(more);
        }
    }

    // Add category filter if present
    if let Some(ref category) = filter.category {
        if category.has_condition() {
            let (sql, more) = category.to_sql_parts();
            conditions.push(sql);
            binds.extend(more);
        }
    }

    // Add shop filter if present
    if let Some(shop_id) = filter.shop_id {
        conditions.push("th.SHOP_ID = ?".to_string());
        binds.push(BindValue::I64(shop_id));
    }

    (conditions.join(" AND "), binds)
}

/// Build complete aggregation SQL query
/// Dispatch to the appropriate query builder based on the grouping.
///
/// - `Account` uses a UNION ALL shape because EXPENSE/INCOME/TRANSFER each
///   touch a different account column. Handled by `build_account_aggregation_query`.
/// - `Category2`, `Category3`, and `Product` group by a column that lives on
///   `TRANSACTIONS_DETAIL`, so the query has to walk the detail rows. These go
///   through `build_detail_query`, which protects against the row-multiplication
///   that comes from joining detail and naively summing `th.TOTAL_AMOUNT`.
/// - Everything else (`Category1`, `Shop`, `Date`) groups on header columns and
///   never joins detail, so the simpler `build_header_query` shape is correct.
pub fn build_query(request: &AggregationRequest, lang: &str) -> (String, Vec<BindValue>) {
    match request.group_by {
        GroupBy::Account => build_account_aggregation_query(request),
        GroupBy::Category2 | GroupBy::Category3 | GroupBy::Product => {
            build_detail_query(request, lang)
        }
        GroupBy::Category1 | GroupBy::Shop | GroupBy::Date => {
            build_header_query(request, lang)
        }
    }
}

/// Build the aggregation query for header-level groupings (`Category1`, `Shop`,
/// `Date`). Sums `th.TOTAL_AMOUNT` directly because no detail join takes place.
/// Bind order: joins-binds (lang) → where-binds (user_id, date, [amount], [category], [shop_id]) → [limit].
fn build_header_query(request: &AggregationRequest, lang: &str) -> (String, Vec<BindValue>) {
    let select_clause = request.group_by.to_select_clause();
    let group_by_clause = request.group_by.to_group_by_clause();
    let (where_clause, where_binds) = build_where_clause(request.user_id, &request.filter);
    let order_field = request.order_by.to_order_by_field();
    let sort_order = request.sort_order.to_sql();

    let (joins, join_binds) = build_join_clauses(&request.group_by, request.user_id, lang);

    let mut sql = format!(
        r#"
SELECT
    {},
    SUM(
        CASE
            WHEN th.CATEGORY1_CODE = 'EXPENSE' THEN -th.TOTAL_AMOUNT
            WHEN th.CATEGORY1_CODE = 'INCOME' THEN th.TOTAL_AMOUNT
            WHEN th.CATEGORY1_CODE = 'TRANSFER' THEN 0
            ELSE th.TOTAL_AMOUNT
        END
    ) as total_amount,
    COUNT(*) as count,
    CAST(AVG(
        CASE
            WHEN th.CATEGORY1_CODE = 'EXPENSE' THEN -th.TOTAL_AMOUNT
            WHEN th.CATEGORY1_CODE = 'INCOME' THEN th.TOTAL_AMOUNT
            WHEN th.CATEGORY1_CODE = 'TRANSFER' THEN 0
            ELSE th.TOTAL_AMOUNT
        END
    ) AS INTEGER) as avg_amount
FROM TRANSACTIONS_HEADER th
{}
WHERE {}
GROUP BY {}
ORDER BY {} {}
"#,
        select_clause, joins, where_clause, group_by_clause, order_field, sort_order
    );

    let mut binds = join_binds;
    binds.extend(where_binds);

    if let Some(limit) = request.limit {
        sql.push_str("LIMIT ?");
        binds.push(BindValue::I64(limit as i64));
    }

    (sql, binds)
}

/// Build the aggregation query for detail-level groupings (`Category2`,
/// `Category3`, `Product`).
///
/// The query has three layers, each with a distinct responsibility:
///
/// 1. **Innermost** — for every `(transaction × group_key × tax_rate ×
///    rounding_type)` combination, sums the pre-tax amounts that need a tax
///    calculation (`pretax_sum`) separately from the amounts that are already
///    integer-final (`already_included_sum`). The split lets us avoid the
///    "one rounding per detail row" error accumulation that the previous
///    `SUM(th.TOTAL_AMOUNT)` shape produced when it was joined to detail.
/// 2. **Middle** — applies the transaction's `TAX_ROUNDING_TYPE` exactly once
///    per `(transaction, group, tax_rate)` slice: the pre-tax sum is grossed
///    up by `(100 + tax_rate)/100` and rounded according to the chosen mode,
///    then added to the already-included sum, then signed by `CATEGORY1_CODE`.
///    The output is an integer `signed_amount` per slice.
/// 3. **Outer** — groups the integer slices by `(group_key, group_name)` and
///    sums them. No further rounding happens here, so cross-transaction
///    aggregation is exact.
///
/// The amount classification follows the rule we agreed on with the data:
/// a row counts as "already tax-included" when the *header* declares the
/// ledger as tax-included (`TAX_INCLUDED_TYPE == TAX_INCLUDED = 0` — the
/// user typed the AMOUNT column as prices that already contain tax), OR
/// when `TAX_RATE = 0` (gross-up has no effect anyway), OR when
/// `AMOUNT = AMOUNT_INCLUDING_TAX` and the tax-included column is
/// actually populated (a single already-included row inside an otherwise
/// tax-excluded ledger). Everything else is treated as pre-tax and
/// grossed up, matching the authoritative Rust classifier in
/// `services::transaction::calculate_recommended_total_with_settings`.
///
/// The `TAX_INCLUDED_TYPE` branch is what closes Fable-5 review #3:
/// legacy rows (v2.0 or earlier) whose `AMOUNT_INCLUDING_TAX` is NULL
/// under a tax-included header used to fall through to the pre-tax bucket
/// and get grossed up a second time, silently over-reporting the amount
/// by the tax rate. The header-level check catches those rows before
/// per-detail heuristics ever run.
///
/// The two branches remain exhaustive complements so no row silently
/// drops out of both sums.
fn build_detail_query(request: &AggregationRequest, lang: &str) -> (String, Vec<BindValue>) {
    let (where_clause, where_binds) = build_where_clause(request.user_id, &request.filter);
    let order_field = request.order_by.to_order_by_field();
    let sort_order = request.sort_order.to_sql();
    let (group_key_expr, group_name_expr, joins, join_binds) =
        build_detail_group_pieces(&request.group_by, lang);

    let mut sql = format!(
        r#"
SELECT
    sub.group_key,
    sub.group_name,
    SUM(sub.signed_amount) AS total_amount,
    COUNT(DISTINCT sub.txn_id) AS count,
    -- Derive avg_amount from total / txn_count so `avg × count == total`
    -- always holds. `AVG(sub.signed_amount)` averages over `sub` rows, which
    -- are one per (txn × group × tax_rate × rounding_type) slice: a single
    -- transaction with 8 % and 10 % details produces two `sub` rows but only
    -- one distinct `txn_id`, so the raw AVG halves the reported average.
    -- The multiplication by 1.0 promotes the numerator to REAL before the
    -- division, preserving the truncate-toward-zero semantics of the prior
    -- `CAST(AVG(...) AS INTEGER)` shape.
    CAST(SUM(sub.signed_amount) * 1.0 / COUNT(DISTINCT sub.txn_id) AS INTEGER) AS avg_amount
FROM (
    SELECT
        agg.txn_id,
        agg.group_key,
        agg.group_name,
        CASE agg.cat1
            WHEN 'EXPENSE' THEN -1
            WHEN 'TRANSFER' THEN 0
            ELSE 1
        END
        * (
            agg.already_included_sum
            + CASE agg.rounding_type
                -- floor: integer division on positive integers truncates
                -- towards zero, which equals floor when the operands are
                -- positive (which they are: pretax_sum and (100 + rate)
                -- are both non-negative).
                WHEN 0 THEN agg.pretax_sum * (100 + agg.tax_rate) / 100
                -- half-away-from-zero: lift to REAL via 100.0 / 100.0 so
                -- ROUND() can see the fractional part.
                WHEN 1 THEN CAST(ROUND(agg.pretax_sum * (100.0 + agg.tax_rate) / 100.0) AS INTEGER)
                -- ceil for positive integers: (n + 99) / 100 with integer
                -- division. The historical `-CAST(-n / 100 AS INTEGER)`
                -- idiom looks plausible but is wrong here — SQLite's
                -- integer division truncates towards zero, which on the
                -- negated operand acts as ceil, so the double-negation
                -- collapses back to floor and shaves off the very 1-yen
                -- that ceil was supposed to add. Mirrors the Rust port.
                WHEN 2 THEN (agg.pretax_sum * (100 + agg.tax_rate) + 99) / 100
                ELSE agg.pretax_sum * (100 + agg.tax_rate) / 100
            END
        ) AS signed_amount
    FROM (
        SELECT
            th.TRANSACTION_ID AS txn_id,
            {gk} AS group_key,
            {gn} AS group_name,
            th.CATEGORY1_CODE AS cat1,
            td.TAX_RATE AS tax_rate,
            th.TAX_ROUNDING_TYPE AS rounding_type,
            SUM(CASE
                -- Fable-5 #3: header-level tax-included declaration wins
                -- over the per-detail heuristic. Without this, legacy
                -- rows (AMOUNT_INCLUDING_TAX IS NULL, tax-included
                -- header) fall into the pretax bucket below and get
                -- grossed up again, silently over-reporting by the tax
                -- rate. The `{tax_included}` placeholder is
                -- `consts::TAX_INCLUDED` interpolated at build time —
                -- CodeRabbit #124 review: hard-coding a bare `0` here
                -- couples the SQL to a specific numeric encoding of the
                -- constant and would silently drift if the constant is
                -- ever renumbered.
                WHEN th.TAX_INCLUDED_TYPE = {tax_included}
                  OR td.TAX_RATE = 0
                  OR (td.AMOUNT_INCLUDING_TAX IS NOT NULL
                      AND td.AMOUNT = td.AMOUNT_INCLUDING_TAX)
                THEN td.AMOUNT ELSE 0
            END) AS already_included_sum,
            SUM(CASE
                WHEN th.TAX_INCLUDED_TYPE != {tax_included}
                  AND td.TAX_RATE > 0
                  AND (td.AMOUNT_INCLUDING_TAX IS NULL
                       OR td.AMOUNT != td.AMOUNT_INCLUDING_TAX)
                THEN td.AMOUNT ELSE 0
            END) AS pretax_sum
        FROM TRANSACTIONS_HEADER th
        INNER JOIN TRANSACTIONS_DETAIL td
            ON th.USER_ID = td.USER_ID AND th.TRANSACTION_ID = td.TRANSACTION_ID
        {joins}
        WHERE {where_clause}
        GROUP BY th.TRANSACTION_ID, {gk}, {gn}, td.TAX_RATE, th.TAX_ROUNDING_TYPE, th.CATEGORY1_CODE
    ) agg
) sub
GROUP BY sub.group_key, sub.group_name
ORDER BY {order_field} {sort_order}
"#,
        gk = group_key_expr,
        gn = group_name_expr,
        joins = joins,
        where_clause = where_clause,
        order_field = order_field,
        sort_order = sort_order,
        tax_included = crate::consts::TAX_INCLUDED,
    );

    // Bind order matches the placeholder order inside the SQL string above:
    // inner subquery's join clauses (lang bind) come before its WHERE clause.
    let mut binds = join_binds;
    binds.extend(where_binds);

    if let Some(limit) = request.limit {
        sql.push_str("LIMIT ?");
        binds.push(BindValue::I64(limit as i64));
    }

    (sql, binds)
}

/// Resolve the per-grouping pieces that the detail-level subquery needs:
/// the SQL expression that produces the group key, the expression for the
/// human-readable name, and the JOIN clauses for the ancillary tables that
/// feed the name expression.
///
/// Only called from `build_detail_query`; panicking on non-detail variants is
/// a deliberate signal that the dispatcher in `build_query` is wrong, not a
/// runtime failure mode users could ever hit.
fn build_detail_group_pieces(
    group_by: &GroupBy,
    lang: &str,
) -> (String, String, String, Vec<BindValue>) {
    match group_by {
        GroupBy::Category2 => (
            "td.CATEGORY1_CODE || '/' || td.CATEGORY2_CODE".to_string(),
            "COALESCE(c2i.CATEGORY2_NAME_I18N, c2.CATEGORY2_NAME)".to_string(),
            "LEFT JOIN CATEGORY2 c2 ON td.USER_ID = c2.USER_ID \
             AND td.CATEGORY1_CODE = c2.CATEGORY1_CODE \
             AND td.CATEGORY2_CODE = c2.CATEGORY2_CODE\n\
             LEFT JOIN CATEGORY2_I18N c2i ON c2.USER_ID = c2i.USER_ID \
             AND c2.CATEGORY1_CODE = c2i.CATEGORY1_CODE \
             AND c2.CATEGORY2_CODE = c2i.CATEGORY2_CODE \
             AND c2i.LANG_CODE = ?"
                .to_string(),
            vec![BindValue::Str(lang.to_string())],
        ),
        GroupBy::Category3 => (
            "td.CATEGORY1_CODE || '/' || td.CATEGORY2_CODE || '/' || td.CATEGORY3_CODE"
                .to_string(),
            "COALESCE(c3i.CATEGORY3_NAME_I18N, c3.CATEGORY3_NAME)".to_string(),
            "LEFT JOIN CATEGORY3 c3 ON td.USER_ID = c3.USER_ID \
             AND td.CATEGORY1_CODE = c3.CATEGORY1_CODE \
             AND td.CATEGORY2_CODE = c3.CATEGORY2_CODE \
             AND td.CATEGORY3_CODE = c3.CATEGORY3_CODE\n\
             LEFT JOIN CATEGORY3_I18N c3i ON c3.USER_ID = c3i.USER_ID \
             AND c3.CATEGORY1_CODE = c3i.CATEGORY1_CODE \
             AND c3.CATEGORY2_CODE = c3i.CATEGORY2_CODE \
             AND c3.CATEGORY3_CODE = c3i.CATEGORY3_CODE \
             AND c3i.LANG_CODE = ?"
                .to_string(),
            vec![BindValue::Str(lang.to_string())],
        ),
        GroupBy::Product => (
            "CAST(COALESCE(td.PRODUCT_ID, 0) AS TEXT)".to_string(),
            // Fable-5 review #22 — empty string sentinel, swapped to
            // `i18n.t('common.unspecified')` on the frontend. See
            // the matching comment on the Shop branch above.
            "COALESCE(p.PRODUCT_NAME, '')".to_string(),
            "LEFT JOIN PRODUCTS p ON td.USER_ID = p.USER_ID AND td.PRODUCT_ID = p.PRODUCT_ID"
                .to_string(),
            Vec::new(),
        ),
        _ => unreachable!(
            "build_detail_group_pieces is only valid for Category2/Category3/Product"
        ),
    }
}

/// Build account aggregation query using UNION ALL approach
///
/// Account aggregation requires special handling because:
/// - EXPENSE: uses FROM_ACCOUNT_CODE (money flows out)
/// - INCOME: uses TO_ACCOUNT_CODE (money flows in)
/// - TRANSFER: creates two records - FROM_ACCOUNT (outflow) and TO_ACCOUNT (inflow)
fn build_account_aggregation_query(request: &AggregationRequest) -> (String, Vec<BindValue>) {
    let user_id = request.user_id;
    let (date_sql, date_binds) = request.filter.date.to_sql_parts();
    let order_field = request.order_by.to_order_by_field();
    let sort_order = request.sort_order.to_sql();

    // Build additional filter conditions (amount, shop, scheduled,
    // category). Kept as (sql, binds) pairs so the four UNION ALL
    // branches below can each replay them in the same order without
    // re-running the builders.
    //
    // PR6 (Fable-5 #18): `request.filter.category` used to be silently
    // dropped here, so `group_by = "account"` combined with a category
    // constraint returned every transaction's account flow instead of
    // the filtered subset — a bloated total with no error to trace.
    // `Category1` bindings target `th.CATEGORY1_CODE` (present on
    // TRANSACTIONS_HEADER) and work cleanly. `Category2`/`Category3`
    // bind `td.CATEGORY*_CODE` (see CategoryFilter::to_sql_parts docs),
    // which is unresolved here because this query never joins
    // TRANSACTIONS_DETAIL — SQLite reports `no such column: td.*`
    // and the misuse surfaces fast instead of silently returning the
    // wrong rows.
    let mut additional_conditions: Vec<String> = Vec::new();
    let mut additional_binds: Vec<BindValue> = Vec::new();
    if !request.filter.include_scheduled {
        additional_conditions.push("th.IS_SCHEDULED = 0".to_string());
    }
    if let Some(ref amount) = request.filter.amount {
        if amount.has_condition() {
            let (sql, more) = amount.to_sql_parts();
            additional_conditions.push(sql);
            additional_binds.extend(more);
        }
    }
    if let Some(ref category) = request.filter.category {
        if category.has_condition() {
            let (sql, more) = category.to_sql_parts();
            additional_conditions.push(sql);
            additional_binds.extend(more);
        }
    }
    if let Some(shop_id) = request.filter.shop_id {
        additional_conditions.push("th.SHOP_ID = ?".to_string());
        additional_binds.push(BindValue::I64(shop_id));
    }
    let additional_where = if additional_conditions.is_empty() {
        String::new()
    } else {
        format!(" AND {}", additional_conditions.join(" AND "))
    };

    let mut sql = format!(
        r#"
SELECT
    account_data.account_code as group_key,
    -- Fable-5 review #22 — the NONE account is initialised via
    -- `initialize_none_account` with `template_name_ja` ("指定なし"),
    -- so `a.ACCOUNT_NAME` for it is Japanese regardless of the UI
    -- language. Return an empty string for both the NONE case and
    -- any unresolved account (defensive NULL) so the frontend's
    -- `aggregation-common.js::renderResults` can swap it for
    -- `i18n.t('common.unspecified')` uniformly across en/ja.
    CASE
        WHEN account_data.account_code = 'NONE' THEN ''
        ELSE COALESCE(a.ACCOUNT_NAME, '')
    END as group_name,
    SUM(account_data.amount) as total_amount,
    COUNT(*) as count,
    CAST(AVG(account_data.amount) AS INTEGER) as avg_amount
FROM (
    -- EXPENSE: FROM_ACCOUNT loses money (negative amount)
    SELECT th.FROM_ACCOUNT_CODE as account_code, -th.TOTAL_AMOUNT as amount
    FROM TRANSACTIONS_HEADER th
    WHERE th.USER_ID = ? AND th.CATEGORY1_CODE = 'EXPENSE' AND {date_sql}{additional_where}

    UNION ALL

    -- INCOME: TO_ACCOUNT gains money (positive amount)
    SELECT th.TO_ACCOUNT_CODE as account_code, th.TOTAL_AMOUNT as amount
    FROM TRANSACTIONS_HEADER th
    WHERE th.USER_ID = ? AND th.CATEGORY1_CODE = 'INCOME' AND {date_sql}{additional_where}

    UNION ALL

    -- TRANSFER FROM: FROM_ACCOUNT loses money (negative amount)
    SELECT th.FROM_ACCOUNT_CODE as account_code, -th.TOTAL_AMOUNT as amount
    FROM TRANSACTIONS_HEADER th
    WHERE th.USER_ID = ? AND th.CATEGORY1_CODE = 'TRANSFER' AND {date_sql}{additional_where}

    UNION ALL

    -- TRANSFER TO: TO_ACCOUNT gains money (positive amount)
    SELECT th.TO_ACCOUNT_CODE as account_code, th.TOTAL_AMOUNT as amount
    FROM TRANSACTIONS_HEADER th
    WHERE th.USER_ID = ? AND th.CATEGORY1_CODE = 'TRANSFER' AND {date_sql}{additional_where}
) AS account_data
LEFT JOIN ACCOUNTS a ON a.USER_ID = ? AND a.ACCOUNT_CODE = account_data.account_code
GROUP BY account_data.account_code
ORDER BY {order_field} {sort_order}
"#
    );

    // Bind order mirrors the placeholder order inside the SQL: four UNION
    // ALL branches (each: user_id → date_binds → additional_binds), then
    // the outer LEFT JOIN's `a.USER_ID = ?`.
    let mut binds: Vec<BindValue> = Vec::new();
    for _ in 0..4 {
        binds.push(BindValue::I64(user_id));
        binds.extend(date_binds.clone());
        binds.extend(additional_binds.clone());
    }
    binds.push(BindValue::I64(user_id));

    // Add LIMIT if specified
    if let Some(limit) = request.limit {
        sql.push_str("LIMIT ?");
        binds.push(BindValue::I64(limit as i64));
    }

    (sql, binds)
}

/// Build JOIN clauses based on grouping. Returns the SQL fragment and
/// the bind values that fragment expects (only the CATEGORY1_I18N join
/// binds a value — the `lang` code). Same reachability contract as
/// [`GroupBy::to_select_clause`]: called only from `build_header_query`
/// (Category1/Shop/Date). The four dead arms panic with `unreachable!()`
/// (PR10, Fable-5 #33) so a rerouting caller fails loudly instead of
/// producing a subtly-wrong join graph.
fn build_join_clauses(group_by: &GroupBy, _user_id: i64, lang: &str) -> (String, Vec<BindValue>) {
    match group_by {
        GroupBy::Category1 => (
            r#"
LEFT JOIN CATEGORY1 c1 ON th.USER_ID = c1.USER_ID AND th.CATEGORY1_CODE = c1.CATEGORY1_CODE
LEFT JOIN CATEGORY1_I18N c1i ON c1.USER_ID = c1i.USER_ID AND c1.CATEGORY1_CODE = c1i.CATEGORY1_CODE AND c1i.LANG_CODE = ?
"#
            .to_string(),
            vec![BindValue::Str(lang.to_string())],
        ),
        GroupBy::Shop => (
            r#"
LEFT JOIN SHOPS s ON th.USER_ID = s.USER_ID AND th.SHOP_ID = s.SHOP_ID
"#
            .to_string(),
            Vec::new(),
        ),
        GroupBy::Date => (String::new(), Vec::new()),
        GroupBy::Category2
        | GroupBy::Category3
        | GroupBy::Product
        | GroupBy::Account => unreachable!(
            "build_join_clauses is only called from build_header_query \
             (Category1/Shop/Date); {:?} must go through its dedicated \
             builder — build_detail_query for Category2/3/Product, \
             build_account_aggregation_query for Account.",
            group_by
        ),
    }
}

