    /// End-to-end injection-safety pin for PR5 (Fable-5 #25). A category
    /// filter whose value is a canonical SQLite injection payload
    /// (`FOOD' OR '1'='1`) must be treated as an opaque string literal
    /// after the `format!()` → `.bind()` migration — the aggregator
    /// returns zero rows because no CATEGORY2_CODE actually equals that
    /// literal. If the value were ever re-inlined into the SQL, the
    /// `OR '1'='1` would degenerate the filter to always-true and we
    /// would see the FOOD row (`total_amount == -108`) come back.
    #[tokio::test]
    async fn test_detail_query_binds_category_filter_no_injection() {
        let pool = setup_aggregation_test_db().await;

        let txn = insert_test_header(&pool, 1, 0, 1, 0).await;
        insert_detail(&pool, 1, txn, 1, "FOOD", 100, 8, Some(108)).await;

        let from = NaiveDate::from_ymd_opt(2024, 6, 1).unwrap();
        let to = NaiveDate::from_ymd_opt(2024, 6, 30).unwrap();
        // Use Category1 (a column that does live on TRANSACTIONS_HEADER)
        // so the WHERE clause hits a real column; a malicious literal
        // in Category2/3 would exercise the same bind path but would
        // require a fatter test schema for the inner subquery to
        // resolve the column reference.
        let malicious = "EXPENSE' OR '1'='1";
        let filter = AggregationFilter::new(DateFilter::Between(from, to)).with_category(
            CategoryFilter::Category1(malicious.to_string()),
        );
        let request = AggregationRequest::new(1, filter, GroupBy::Category2);

        let (sql, binds) = build_query(&request, "ja");

        // The payload must NOT appear inline in the SQL; it must be in
        // the bind vec instead.
        assert!(
            !sql.contains(malicious),
            "injection payload leaked into SQL text: {}",
            sql
        );
        assert!(
            binds.iter().any(|b| matches!(b, BindValue::Str(s) if s == malicious)),
            "injection payload must be bound as a literal: {:?}",
            binds
        );

        let results: Vec<AggregationResult> = bind_all(
            sqlx::query_as::<_, AggregationResult>(&sql),
            binds,
        )
        .fetch_all(&pool)
        .await
        .unwrap();

        assert!(
            results.is_empty(),
            "malicious payload must match zero rows (would have been -108 if inlined): {:?}",
            results
        );
    }

