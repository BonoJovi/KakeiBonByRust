    // most filter tests only need to confirm what got bound.
    fn first_str_bind(binds: &[BindValue]) -> &str {
        match binds.first() {
            Some(BindValue::Str(s)) => s.as_str(),
            other => panic!("expected first bind to be Str, got {:?}", other),
        }
    }

