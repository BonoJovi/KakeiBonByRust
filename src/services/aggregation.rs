        // path; we set 0 here so we can prove the detail-side
        // computation stands on its own.
        let txn = insert_test_header(&pool, 1, /*floor*/ 0, /*tax_included*/ 0, 0).await;
        // Legacy row: AMOUNT is the tax-included price (110), TAX_RATE
